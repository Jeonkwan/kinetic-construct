#!/usr/bin/env python3
"""Mirror the canonical specimen and rebuild the consolidated agent context."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent
SITE = 'https://jeonkwan.github.io/kinetic-construct/'
SOURCES = (
    ('Authoring guide', 'reference/guide.md'),
    ('Diagram selection and notation', 'reference/diagram-guide.md'),
    ('Project-local diagram style', 'reference/diagram-style.md'),
    ('Agent skill', 'reference/SKILL.md'),
    ('Explicit-only skill invocation policy', 'reference/agents/openai.yaml'),
    ('Design tokens', 'reference/kinetic-serif.json'),
    ('Stylesheet', 'css/kinetic-serif.css'),
    ('Runtime', 'js/kinetic-serif.js'),
    ('Starter template', 'starter/index.html'),
    ('Complete topology specimen', 'starter/diagram.html'),
    ('Terraform/GCS assumptions and historical source gap', 'reference/architecture-spec.md'),
)


def generated():
    start = '<!-- BEGIN module-state specimen -->'
    end = '<!-- END module-state specimen -->'
    source = (ROOT / 'starter/diagram.html').read_text()
    component = source[source.index(start):source.index(end) + len(end)]
    # These are the only repository-relative URLs in the canonical component.
    for path in ('starter/diagram.html', 'reference/diagram-guide.md', 'reference/architecture-spec.md'):
        component = component.replace(f'href="../{path}"', f'href="{path}"')
    index = (ROOT / 'index.html').read_text()
    index = index[:index.index(start)] + component + index[index.index(end) + len(end):]
    bundle = '''# Kinetic Construct (kinetic-serif v1.2.3) Complete LLM Ingestion Bundle

Canonical site: https://jeonkwan.github.io/kinetic-construct/
Source repository: https://github.com/Jeonkwan/kinetic-construct

Generated by python3 sync_reference.py from the maintained files below.
The topology is a new illustrative teaching model, not deployed infrastructure or recovered missing content.
The historical three-plane enumeration remains unknown. Reusable notation and domain assumptions are separate.
Hosted URLs track deployed main. Local uncommitted changes are not published.
For other projects, use these hosted assets or vendor a fixed revision; relative starter paths assume the repository layout.

```html
<link rel="stylesheet" href="https://jeonkwan.github.io/kinetic-construct/css/kinetic-serif.css" />
<script src="https://jeonkwan.github.io/kinetic-construct/js/kinetic-serif.js" defer></script>
```
'''
    for title, path in SOURCES:
        bundle += f'\n## {title}\nSource: {SITE}{path}\n\n<!-- BEGIN {path} -->\n'
        bundle += (ROOT / path).read_text().rstrip() + f'\n<!-- END {path} -->\n'
    return {'index.html': index, 'llms-full.txt': bundle}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files differ; write nothing')
    args = parser.parse_args()
    stale = []
    for path, content in generated().items():
        if (ROOT / path).read_text() != content:
            stale.append(path)
            if not args.check:
                (ROOT / path).write_text(content)
    if args.check and stale:
        raise SystemExit('Stale generated files: ' + ', '.join(stale))
    print(('Checked' if args.check else 'Synchronized') + ' specimen mirror and LLM bundle')


if __name__ == '__main__':
    main()
